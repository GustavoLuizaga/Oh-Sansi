    <script>
        // Script para acordeones
        document.querySelectorAll('.articulo__header').forEach(header => {
            header.addEventListener('click', () => {
                const body = header.nextElementSibling;
                body.style.display = body.style.display === 'none' ? 'block' : 'none';
                header.classList.toggle('articulo__header--active');
            });
        });

        // Script para navegación activa
        window.addEventListener('scroll', () => {
            const sections = document.querySelectorAll('.capitulo');
            let current = '';
            
            sections.forEach(section => {
                const sectionTop = section.offsetTop;
                if (pageYOffset >= (sectionTop - 100)) {
                    current = section.getAttribute('id');
                }
            });
            
            document.querySelectorAll('.sidebar__link').forEach(link => {
                link.classList.remove('sidebar__link--active');
                if (link.getAttribute('href') === `#${current}`) {
                    link.classList.add('sidebar__link--active');
                }
            });
        });
    </script>
