function addUserMessageFAQ(message) {
    const chatMessages = document.getElementById('chatMessagesFAQ');
    const messageDiv = document.createElement('div');
    messageDiv.className = 'message user-message';
    messageDiv.innerHTML = message;
    chatMessages.appendChild(messageDiv);
    chatMessages.scrollTop = chatMessages.scrollHeight;
}

function addBotMessageFAQ(message) {
    const chatMessages = document.getElementById('chatMessagesFAQ');
    const messageDiv = document.createElement('div');
    messageDiv.className = 'message bot-message';
    messageDiv.innerHTML = message;
    chatMessages.appendChild(messageDiv);
    chatMessages.scrollTop = chatMessages.scrollHeight;
}

function askQuestionFAQ(question) {
    addUserMessageFAQ(question);
    let found = false;
    for (const key in faqDatabaseFAQ) {
        if (faqDatabaseFAQ[key].question.toLowerCase() === question.toLowerCase()) {
            setTimeout(() => {
                addBotMessageFAQ(faqDatabaseFAQ[key].answer);
            }, 600);
            found = true;
            break;
        }
    }
    if (!found) {
        let response = "No encontré una respuesta específica. Opciones rápidas:<br>";
        const quickOptions = [];
        for (const key in faqDatabaseFAQ) {
            quickOptions.push(`<div class=\"quick-option\" style=\"font-size:12px;display:inline-block;margin:3px;\" onclick=\"askQuestionFAQ('${faqDatabaseFAQ[key].question}')\">${faqDatabaseFAQ[key].question}</div>`);
        }
        response += quickOptions.join('');
        setTimeout(() => {
            addBotMessageFAQ(response);
        }, 600);
    }
}

document.addEventListener('DOMContentLoaded', function() {
    if(document.getElementById('sendButtonFAQ')) {
        document.getElementById('sendButtonFAQ').addEventListener('click', function() {
            const userInput = document.getElementById('userInputFAQ');
            const question = userInput.value.trim();
            if (question !== '') {
                askQuestionFAQ(question);
                userInput.value = '';
            }
        });
        document.getElementById('userInputFAQ').addEventListener('keypress', function(e) {
            if (e.key === 'Enter') {
                document.getElementById('sendButtonFAQ').click();
            }
        });
    }
});

function abrirModalFAQ() {
    document.getElementById('modalFAQ').style.display = 'flex';
    document.getElementById('chatMessagesFAQ').innerHTML = '';
    setTimeout(() => {
        addBotMessageFAQ("¡Hola! Soy el asistente virtual. ¿En qué puedo ayudarte?<br>Puedes escribir tu pregunta o seleccionar una opción rápida.");
    }, 300);
}

function cerrarModalFAQ() {
    document.getElementById('modalFAQ').style.display = 'none';
}

document.addEventListener('mousedown', function(e) {
    const modal = document.getElementById('modalFAQ');
    const content = document.querySelector('.modal-faq-content');
    if (modal && modal.style.display === 'flex') {
        if (!content.contains(e.target)) {
            cerrarModalFAQ();
        }
    }
});

window.abrirModalFAQ = abrirModalFAQ;
window.cerrarModalFAQ = cerrarModalFAQ;
window.askQuestionFAQ = askQuestionFAQ;

